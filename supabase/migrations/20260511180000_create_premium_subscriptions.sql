-- ============================================================
-- HUB PLANNER - Premium Subscription System
-- ============================================================

-- 1. Bảng gói Premium
CREATE TABLE IF NOT EXISTS "public"."premium_plans" (
    "id" text NOT NULL PRIMARY KEY,
    "name" text NOT NULL,
    "description" text,
    "price" integer NOT NULL DEFAULT 0, -- VND
    "duration_days" integer NOT NULL DEFAULT 30,
    "features" jsonb DEFAULT '[]'::jsonb,
    "is_active" boolean DEFAULT true,
    "created_at" timestamp with time zone DEFAULT now()
);

ALTER TABLE "public"."premium_plans" OWNER TO "postgres";

-- 2. Bảng đăng ký Premium của người dùng
CREATE TABLE IF NOT EXISTS "public"."user_subscriptions" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id" uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    "plan_id" text NOT NULL REFERENCES public.premium_plans(id),
    "status" text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'expired', 'cancelled', 'pending')),
    "started_at" timestamp with time zone DEFAULT now(),
    "expires_at" timestamp with time zone NOT NULL,
    "payment_method" text, -- 'bank_transfer', 'momo', 'zalopay', 'admin_grant'
    "payment_ref" text, -- Mã giao dịch
    "amount_paid" integer DEFAULT 0,
    "auto_renew" boolean DEFAULT false,
    "cancelled_at" timestamp with time zone,
    "created_at" timestamp with time zone DEFAULT now(),
    "updated_at" timestamp with time zone DEFAULT now()
);

ALTER TABLE "public"."user_subscriptions" OWNER TO "postgres";

-- Index cho truy vấn nhanh
CREATE INDEX IF NOT EXISTS idx_user_subscriptions_user_id ON public.user_subscriptions(user_id);
CREATE INDEX IF NOT EXISTS idx_user_subscriptions_status ON public.user_subscriptions(status);
CREATE INDEX IF NOT EXISTS idx_user_subscriptions_expires_at ON public.user_subscriptions(expires_at);

-- 3. Bảng theo dõi usage AI (rate limiting cho Free users)
CREATE TABLE IF NOT EXISTS "public"."ai_usage_daily" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id" uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    "date" date NOT NULL DEFAULT CURRENT_DATE,
    "message_count" integer NOT NULL DEFAULT 0,
    "created_at" timestamp with time zone DEFAULT now(),
    UNIQUE(user_id, date)
);

ALTER TABLE "public"."ai_usage_daily" OWNER TO "postgres";

CREATE INDEX IF NOT EXISTS idx_ai_usage_daily_user_date ON public.ai_usage_daily(user_id, date);

-- 4. Bảng lịch sử thanh toán
CREATE TABLE IF NOT EXISTS "public"."payment_history" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id" uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    "subscription_id" bigint REFERENCES public.user_subscriptions(id),
    "amount" integer NOT NULL,
    "method" text NOT NULL,
    "transaction_ref" text,
    "status" text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'failed', 'refunded')),
    "note" text,
    "confirmed_by" uuid, -- Admin xác nhận
    "created_at" timestamp with time zone DEFAULT now()
);

ALTER TABLE "public"."payment_history" OWNER TO "postgres";

-- 5. Enable RLS
ALTER TABLE "public"."premium_plans" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."user_subscriptions" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."ai_usage_daily" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."payment_history" ENABLE ROW LEVEL SECURITY;

-- 6. RLS Policies

-- premium_plans: ai cũng có thể xem
CREATE POLICY "Everyone can view active plans" ON public.premium_plans
    FOR SELECT USING (is_active = true);

CREATE POLICY "Admins can manage plans" ON public.premium_plans
    FOR ALL USING (
        EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin')
    );

-- user_subscriptions: chỉ chủ sở hữu + admin
CREATE POLICY "Users can view own subscriptions" ON public.user_subscriptions
    FOR SELECT USING (user_id = auth.uid());

CREATE POLICY "Admins can manage all subscriptions" ON public.user_subscriptions
    FOR ALL USING (
        EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin')
    );

-- ai_usage_daily: chỉ chủ sở hữu
CREATE POLICY "Users can view own usage" ON public.ai_usage_daily
    FOR SELECT USING (user_id = auth.uid());

CREATE POLICY "Users can insert own usage" ON public.ai_usage_daily
    FOR INSERT WITH CHECK (user_id = auth.uid());

CREATE POLICY "Users can update own usage" ON public.ai_usage_daily
    FOR UPDATE USING (user_id = auth.uid());

-- payment_history: chỉ chủ sở hữu + admin
CREATE POLICY "Users can view own payments" ON public.payment_history
    FOR SELECT USING (user_id = auth.uid());

CREATE POLICY "Admins can manage all payments" ON public.payment_history
    FOR ALL USING (
        EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin')
    );

