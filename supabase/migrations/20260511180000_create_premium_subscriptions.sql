-- 8. Function kiểm tra user có Premium không (dùng trong backend)
CREATE OR REPLACE FUNCTION public.is_premium_user(p_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.user_subscriptions
        WHERE user_id = p_user_id
        AND status = 'active'
        AND expires_at > now()
        AND plan_id != 'free'
    );
$$;

-- 9. Function tăng usage count
CREATE OR REPLACE FUNCTION public.increment_ai_usage(p_user_id uuid)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_count integer;
BEGIN
    INSERT INTO public.ai_usage_daily (user_id, date, message_count)
    VALUES (p_user_id, CURRENT_DATE, 1)
    ON CONFLICT (user_id, date)
    DO UPDATE SET message_count = ai_usage_daily.message_count + 1;
    
    SELECT message_count INTO v_count
    FROM public.ai_usage_daily
    WHERE user_id = p_user_id AND date = CURRENT_DATE;
    
    RETURN v_count;
END;
$$;
