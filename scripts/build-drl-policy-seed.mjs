import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { DRL_RULES_2026, DRL_POLICY_VERSION } from '../utils/drlPolicy2026.ts';

const quote = (value) => value === null ? 'NULL' : typeof value === 'number' ? String(value)
  : `'${String(value).replaceAll("'", "''")}'`;
export const buildDrlPolicySeed = () => {
  const columns = ['rule_id','section','rule_group','content','condition_text','points','unit','event_suitable','active','source_version'];
  const rows = DRL_RULES_2026.map((rule) => `(${columns.map((key) => quote(rule[key])).join(',')})`);
  const equal = DRL_RULES_2026.map((rule) => `(SELECT COUNT(*) FROM drl_rules WHERE ${columns.map((key) =>
    `${key} IS ${quote(rule[key])}`).join(' AND ')})=1`).join('\n AND ');
  return `-- Generated by scripts/build-drl-policy-seed.mjs from the verified appendix.\n-- Idempotent, fail on conflicting IDs; never replace history/rules/cache.\nINSERT OR IGNORE INTO drl_rules (${columns.join(',')}) VALUES\n${rows.join(',\n')};\nCREATE TABLE IF NOT EXISTS drl_policy_seed_checks (policy_version TEXT PRIMARY KEY REFERENCES drl_policy_versions(policy_version), verified INTEGER NOT NULL CHECK(verified=1));\nINSERT INTO drl_policy_seed_checks(policy_version,verified) SELECT ${quote(DRL_POLICY_VERSION)}, CASE WHEN\n ${equal}\n AND (SELECT COUNT(*) FROM drl_rules WHERE source_version=${quote(DRL_POLICY_VERSION)})=46\n THEN 1 ELSE 0 END ON CONFLICT(policy_version) DO UPDATE SET verified=excluded.verified;\n`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) throw new Error('This generator only writes the local SQL artifact. No remote execution.');
  await writeFile(new URL('../cloudflare/migrations/0059_seed_drl_policy_2026.sql', import.meta.url), buildDrlPolicySeed());
  console.log('Generated local idempotent policy seed. No database accessed.');
}
